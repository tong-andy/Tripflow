import { readFileSync, writeFileSync } from 'node:fs';

const [inputPath, outputPath] = process.argv.slice(2);
if (!inputPath || !outputPath) {
  throw new Error('Usage: node scripts/generate-world-svg.mjs input.geojson output.svg');
}

const source = JSON.parse(readFileSync(inputPath, 'utf8'));
const width = 1000;
const height = 500;

function point([longitude, latitude]) {
  const x = ((longitude + 180) / 360) * width;
  const y = ((90 - latitude) / 180) * height;
  return `${x.toFixed(1)} ${y.toFixed(1)}`;
}

function ringPath(ring) {
  if (!ring.length) return '';
  return `M${point(ring[0])}${ring.slice(1).map((coordinate) => `L${point(coordinate)}`).join('')}Z`;
}

function geometryPath(geometry) {
  if (geometry.type === 'Polygon') {
    return geometry.coordinates.map(ringPath).join('');
  }
  if (geometry.type === 'MultiPolygon') {
    return geometry.coordinates.flatMap((polygon) => polygon.map(ringPath)).join('');
  }
  return '';
}

const paths = source.features
  .map((feature) => {
    const name = String(feature.properties?.ADMIN ?? feature.properties?.NAME ?? '');
    const iso = String(feature.properties?.ADM0_A3 ?? feature.properties?.ISO_A3 ?? '');
    const path = geometryPath(feature.geometry);
    return path ? `<path id="country-${iso}" data-country="${name.replaceAll('&', '&amp;').replaceAll('"', '&quot;')}" d="${path}"/>` : '';
  })
  .filter(Boolean)
  .join('');

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Natural Earth Admin 0 Countries, 1:110m. Public domain. Generated by scripts/generate-world-svg.mjs. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" role="img" aria-label="World country boundaries">
  <g fill="#cbd4cf" stroke="#aebbb4" stroke-width="0.8" stroke-linejoin="round">${paths}</g>
</svg>
`;

writeFileSync(outputPath, svg);
